// Helper to shuffle items for a randomized 10-question session with guaranteed balance
export function getRandomGameDeck(count: number = 10): GameItem[] {
  const aiItems = [...GAME_ITEMS.filter(i => i.answer === 'AI')].sort(() => Math.random() - 0.5);
  const realItems = [...GAME_ITEMS.filter(i => i.answer === 'REAL')].sort(() => Math.random() - 0.5);
  
  const half = Math.floor(count / 2);
  const selected = [...aiItems.slice(0, half), ...realItems.slice(0, count - half)];
  return selected.sort(() => Math.random() - 0.5);
}
